"""Godot 4 export helpers: material variant params → ShaderMaterial resource (.tres)."""

from __future__ import annotations

from typing import Any

from .models import EntityDoc, ParamSpec

SHADER_DIR = "res://shaders"


def _value(spec: ParamSpec, value: Any) -> str:
    if spec.type == "bool":
        return "true" if value else "false"
    if spec.type == "int":
        return str(int(value))
    if spec.type == "float":
        return f"{float(value):.6g}"
    if spec.type == "color":
        h = str(value).lstrip("#")
        r, g, b = (int(h[i:i + 2], 16) / 255 for i in (0, 2, 4))
        return f"Color({r:.4f}, {g:.4f}, {b:.4f}, 1)"
    # enum → index (Godot uniforms cannot be strings)
    return str((spec.values or []).index(value))


def godot_tres(doc: EntityDoc, params: dict[str, Any], label: str) -> str:
    """ShaderMaterial using res://shaders/<shader>.gdshader; the hull outline goes into next_pass.

    Params prefixed with `outline_` feed the outline pass; everything else the surface shader.
    """
    shader = doc.shader or doc.id
    surface = {k: v for k, v in params.items() if not k.startswith("outline_")}
    outline = {k: v for k, v in params.items() if k.startswith("outline_")}
    mode = params.get("outline_mode")
    hull = mode == "hull"
    lines = [f'[gd_resource type="ShaderMaterial" load_steps={4 if hull else 2} format=3]', "",
             f'; generated by Voxel Asset Registry from {label}',
             f'[ext_resource type="Shader" path="{SHADER_DIR}/{shader}.gdshader" id="1"]']
    if hull:
        lines += [f'[ext_resource type="Shader" path="{SHADER_DIR}/{shader}_outline.gdshader" id="2"]', "",
                  '[sub_resource type="ShaderMaterial" id="outline"]', 'render_priority = -1', 'shader = ExtResource("2")']
        lines += [f"shader_parameter/{k} = {_value(doc.params[k], v)}" for k, v in outline.items() if k != "outline_mode"]
    lines += ["", "[resource]", 'shader = ExtResource("1")']
    if hull:
        lines.append('next_pass = SubResource("outline")')
    lines += [f"shader_parameter/{k} = {_value(doc.params[k], v)}" for k, v in surface.items()]
    return "\n".join(lines) + "\n"
